// The blog (issue #1): src/app/content/blog/<slug>/{en,it}.md, turned into src/app/content/blog.generated.ts (git-ignored)
// before every build, so a visitor downloads HTML and no Markdown parser. Stops the build on an article that is not
// complete in both languages.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { Marked } from 'marked';

export const DIR = 'src/app/content/blog';
export const OUT = 'src/app/content/blog.generated.ts';
const LOCALES = ['en', 'it'];
const REQUIRED = ['title', 'description', 'date'];
const OPTIONAL = ['updated', 'project', 'linkedin'];
// the same in both languages: they are facts about the article, not words
const SHARED = ['date', 'updated', 'project'];
const WORDS_PER_MINUTE = 220;

/** Splits `---` frontmatter (flat `key: value` lines) from the body. */
export function parseArticle(text, where) {
  const match = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(text.replace(/\r\n/g, '\n'));
  if (!match) throw new Error(`${where}: no frontmatter`);
  const meta = {};
  for (const line of match[1].split('\n')) {
    if (!line.trim()) continue;
    const pair = /^(\w+):\s*(.*)$/.exec(line);
    if (!pair) throw new Error(`${where}: frontmatter line "${line}" is not key: value`);
    if (![...REQUIRED, ...OPTIONAL].includes(pair[1])) throw new Error(`${where}: unknown field "${pair[1]}"`);
    meta[pair[1]] = pair[2].trim().replace(/^(["'])(.*)\1$/, '$2');
  }
  for (const key of REQUIRED) if (!meta[key]) throw new Error(`${where}: "${key}" is missing`);
  for (const key of ['date', 'updated']) {
    if (meta[key] !== undefined && (!/^\d{4}-\d{2}-\d{2}$/.test(meta[key]) || Number.isNaN(Date.parse(meta[key])))) {
      throw new Error(`${where}: "${key}" is not a date (YYYY-MM-DD)`);
    }
  }
  return { meta, body: match[2].trim() };
}

// a code block becomes its own part, drawn by the site's code block component with its copy button (issue #191); the
// marker below stands in for it in the HTML between
const CODE = /<!--code:(\d+)-->\n?/;
let blocks = [];
const marked = new Marked({
  renderer: {
    code({ text, lang }) {
      blocks.push({ code: text, ...(lang ? { lang } : {}) });
      return `<!--code:${String(blocks.length - 1)}-->\n`;
    },
  },
});

/** The article as parts: runs of HTML, and code blocks with their raw text. */
export function articleParts(body) {
  blocks = [];
  const pieces = marked.parse(body).split(CODE);
  const parts = [];
  pieces.forEach((piece, i) => {
    if (i % 2) parts.push(blocks[Number(piece)]);
    else if (piece.trim()) parts.push({ html: piece });
  });
  return parts;
}

export const minutes = (body) => Math.max(1, Math.ceil(body.split(/\s+/).filter(Boolean).length / WORDS_PER_MINUTE));

/** `sources`: { slug: { en: text, it: text } }. Returns { en: Article[], it: Article[] }, newest first. */
export function buildBlog(sources, projectSlugs) {
  const blog = Object.fromEntries(LOCALES.map((l) => [l, []]));
  for (const [slug, files] of Object.entries(sources)) {
    const parsed = {};
    for (const locale of LOCALES) {
      if (!files[locale]) throw new Error(`blog/${slug}: ${locale}.md is missing (every article is in both languages)`);
      parsed[locale] = parseArticle(files[locale], `blog/${slug}/${locale}.md`);
    }
    for (const key of SHARED) {
      if (parsed.en.meta[key] !== parsed.it.meta[key]) throw new Error(`blog/${slug}: "${key}" differs between en.md and it.md`);
    }
    const { project } = parsed.en.meta;
    if (project && !projectSlugs.includes(project)) throw new Error(`blog/${slug}: project "${project}" is not a case study`);
    for (const locale of LOCALES) {
      const { meta, body } = parsed[locale];
      const label = (d) => new Intl.DateTimeFormat(locale === 'it' ? 'it-IT' : 'en-GB', { dateStyle: 'long', timeZone: 'UTC' }).format(new Date(d));
      blog[locale].push({
        slug,
        title: meta.title,
        description: meta.description,
        date: meta.date,
        dateLabel: label(meta.date),
        ...(meta.updated ? { updated: meta.updated } : {}),
        ...(project ? { project } : {}),
        ...(meta.linkedin ? { linkedin: meta.linkedin } : {}),
        minutes: minutes(body),
        parts: articleParts(body),
        markdown: body,
      });
    }
  }
  for (const locale of LOCALES) blog[locale].sort((a, b) => b.date.localeCompare(a.date) || a.slug.localeCompare(b.slug));
  return blog;
}

export function moduleSource(blog) {
  return `// Generated by scripts/blog.mjs from src/app/content/blog. Do not edit.\nimport type { Article } from './content.model';\n\nexport const BLOG: Readonly<Record<'en' | 'it', readonly Article[]>> = ${JSON.stringify(blog, null, 2)};\n`;
}

export async function readSources(dir = DIR) {
  const sources = {};
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    sources[entry.name] = {};
    for (const locale of LOCALES) {
      const text = await readFile(join(dir, entry.name, `${locale}.md`), 'utf8').catch(() => undefined);
      if (text !== undefined) sources[entry.name][locale] = text;
    }
  }
  return sources;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  // run with --import ./scripts/ts-resolve.mjs, like postbuild.mjs
  const { CONTENT_EN } = await import('../src/app/content/content.en.ts');
  const blog = buildBlog(await readSources(), CONTENT_EN.projects.map((p) => p.slug));
  const next = moduleSource(blog);
  // unchanged file, untouched: a dev server would rebuild on every write
  if ((await readFile(OUT, 'utf8').catch(() => '')) !== next) await writeFile(OUT, next);
  console.log(`blog: ${String(blog.en.length)} articles in both languages`);
}
