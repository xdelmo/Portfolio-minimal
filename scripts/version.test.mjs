import assert from 'node:assert/strict';
import { test } from 'node:test';
import { moduleSource, parseVersion } from './version.mjs';

test('parseVersion extracts a valid semver version string', () => {
  assert.equal(parseVersion(JSON.stringify({ version: '2.1.0' })), '2.1.0');
  assert.equal(parseVersion({ version: '2.1.0-beta.1' }), '2.1.0-beta.1');
});

test('parseVersion throws on invalid, missing or non-semver version', () => {
  assert.throws(() => parseVersion({}), /Invalid or missing version/);
  assert.throws(() => parseVersion({ version: '' }), /Invalid or missing version/);
  assert.throws(() => parseVersion({ version: 'v2.1.0' }), /Invalid or missing version/);
  assert.throws(() => parseVersion('{ invalid json }'), SyntaxError);
});

test('moduleSource generates TypeScript export with APP_VERSION constant', () => {
  const code = moduleSource('2.1.0');
  assert.equal(
    code,
    "// Generated by scripts/version.mjs: the application release version. Do not edit.\nexport const APP_VERSION = '2.1.0';\n",
  );
});
