// The release version of the application (issue #291).
// Reads version from package.json and writes src/app/core/version.generated.ts (git-ignored).
import { readFile, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

export const OUT = 'src/app/core/version.generated.ts';
export const PACKAGE_JSON = 'package.json';

const SEMVER = /^\d+\.\d+\.\d+(-[\w.-]+)?$/;

/** Extracts and validates the version string from package.json text or parsed object. */
export function parseVersion(content) {
  const pkg = typeof content === 'string' ? JSON.parse(content) : content;
  const version = pkg?.version;
  if (!version || typeof version !== 'string' || !SEMVER.test(version)) {
    throw new Error(`Invalid or missing version in package.json: ${JSON.stringify(version)}`);
  }
  return version;
}

export function moduleSource(version) {
  return `// Generated by scripts/version.mjs: the application release version. Do not edit.\nexport const APP_VERSION = '${version}';\n`;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const raw = await readFile(PACKAGE_JSON, 'utf8');
  const version = parseVersion(raw);
  const code = moduleSource(version);
  await writeFile(OUT, code);
}
