import assert from 'node:assert/strict';
import { test } from 'node:test';
import { buildBlog, minutes, moduleSource, parseArticle } from './blog.mjs';

const md = (fields, body = 'Some words.') => `---\n${Object.entries(fields).map(([k, v]) => `${k}: ${v}`).join('\n')}\n---\n${body}\n`;
const fields = { title: 'A title: with a colon', description: 'What it is about', date: '2026-10-11', project: 'apexflow' };
const both = (en = fields, it = fields, body) => ({ en: md(en, body), it: md(it, body) });

test('parseArticle reads flat frontmatter, keeping colons in values', () => {
  const { meta, body } = parseArticle(md(fields, '# Hi'), 'x');
  assert.equal(meta.title, 'A title: with a colon');
  assert.equal(body, '# Hi');
});

test('parseArticle stops on a missing field, an unknown one or a bad date', () => {
  assert.throws(() => parseArticle(md({ ...fields, title: '' }), 'x'), /"title" is missing/);
  assert.throws(() => parseArticle(md({ ...fields, tags: 'a' }), 'x'), /unknown field "tags"/);
  assert.throws(() => parseArticle(md({ ...fields, date: '11/10/2026' }), 'x'), /not a date/);
  assert.throws(() => parseArticle('no frontmatter', 'x'), /no frontmatter/);
});

test('every article is in both languages, with the same dates and project', () => {
  assert.throws(() => buildBlog({ a: { en: md(fields) } }, ['apexflow']), /it\.md is missing/);
  assert.throws(() => buildBlog({ a: both(fields, { ...fields, date: '2026-10-12' }) }, ['apexflow']), /"date" differs/);
  assert.throws(() => buildBlog({ a: both() }, ['other']), /project "apexflow" is not a case study/);
});

test('articles come newest first, with the date in words in their language', () => {
  const blog = buildBlog({ old: both({ ...fields, date: '2026-01-02' }, { ...fields, date: '2026-01-02' }), recent: both() }, ['apexflow']);
  assert.deepEqual(blog.en.map((a) => a.slug), ['recent', 'old']);
  assert.equal(blog.en[1].dateLabel, '2 January 2026');
  assert.equal(blog.it[1].dateLabel, '2 gennaio 2026');
});

test('code blocks are escaped and reachable with the keyboard', () => {
  const [article] = buildBlog({ a: both(fields, fields, '```ts\nconst a = 1 < 2;\n```') }, ['apexflow']).en;
  assert.match(article.html, /<pre tabindex="0"><code class="language-ts">const a = 1 &lt; 2;<\/code><\/pre>/);
});

test('reading time rounds up, at least one minute', () => {
  assert.equal(minutes('word'), 1);
  assert.equal(minutes(Array(221).fill('w').join(' ')), 2);
});

test('the module is typed by the Article model', () => {
  assert.match(moduleSource({ en: [], it: [] }), /^\/\/ Generated by scripts\/blog\.mjs[\s\S]*import type \{ Article \}[\s\S]*export const BLOG/);
});
