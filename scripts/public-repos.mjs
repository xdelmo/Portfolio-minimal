// Which of the repositories the content links are public (issue #81). GitHub lists only the public ones
// to a visitor (one API call), so the site links only those: making a repository public (or private again) needs no
// edit, only a build (.github/workflows/repos.yml starts one when the answer changes).
// Writes src/app/content/public-repos.generated.ts (git-ignored); `--print` only prints the list, as JSON.
import { readFile, writeFile } from 'node:fs/promises';
import { setTimeout as sleep } from 'node:timers/promises';
import { pathToFileURL } from 'node:url';

export const OUT = 'src/app/content/public-repos.generated.ts';
const SOURCES = ['src/app/content/content.en.ts', 'src/app/content/content.it.ts'];
const REPO = /https:\/\/github\.com\/xdelmo\/[\w.-]+/g;

/** Every repository URL in the given sources, once each, sorted. */
export function repoUrls(texts) {
  return [...new Set(texts.flatMap((t) => t.match(REPO) ?? []))].sort();
}

export function moduleSource(urls) {
  return `// Generated by scripts/public-repos.mjs: the repositories that answer 200 to a visitor. Do not edit.\nexport const PUBLIC_REPOS: readonly string[] = ${JSON.stringify(urls, null, 2)};\n`;
}

// One API call lists every public repository (issue #350): a HEAD per repository page, all at once, hung on CI's runners.
const API = 'https://api.github.com/users/xdelmo/repos?type=owner&per_page=100';

/** The public repositories' URLs, lower-cased; anything but a 200 is not an answer, and is retried. */
export async function publicList(fetchImpl = globalThis.fetch, tries = 3, token = process.env['GITHUB_TOKEN']) {
  const headers = { accept: 'application/vnd.github+json', ...(token ? { authorization: `Bearer ${token}` } : {}) };
  for (let i = 1; ; i++) {
    try {
      const res = await fetchImpl(API, { headers, signal: globalThis.AbortSignal?.timeout(10000) });
      if (res.status !== 200) throw new Error(`HTTP ${String(res.status)}`);
      const repos = await res.json();
      // ponytail: one page of 100; follow the Link header if the account ever passes 100 public repositories
      if (repos.length >= 100) throw new Error('more than 100 public repositories, add paging');
      return new Set(repos.map((r) => r.html_url.toLowerCase()));
    } catch (error) {
      if (i >= tries) throw new Error(`${API}: ${error instanceof Error ? error.message : String(error)}`, { cause: error });
      await sleep(1000 * i);
    }
  }
}

export async function publicRepos(urls, fetchImpl = globalThis.fetch) {
  const open = await publicList(fetchImpl);
  return urls.filter((url) => open.has(url.toLowerCase()));
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const urls = repoUrls(await Promise.all(SOURCES.map((f) => readFile(f, 'utf8'))));
  let found;
  try {
    found = await publicRepos(urls);
  } catch (error) {
    // a deploy must not guess: it could link a private repository, or drop public ones
    if (process.env['CI'] || process.env['NETLIFY']) {
      console.error(`public-repos: GitHub did not answer, stopping (${error.message})`);
      process.exit(1);
    }
    console.warn(`public-repos: GitHub did not answer, keeping the last list (${error.message})`);
    const kept = await readFile(OUT, 'utf8').catch(() => moduleSource([]));
    await writeFile(OUT, kept);
    process.exit(0);
  }
  if (process.argv.includes('--print')) {
    console.log(JSON.stringify(found));
  } else {
    const next = moduleSource(found);
    // unchanged file, untouched: a dev server would rebuild on every write
    if ((await readFile(OUT, 'utf8').catch(() => '')) !== next) await writeFile(OUT, next);
    console.log(`public-repos: ${String(found.length)} of ${String(urls.length)} linked repositories are public`);
  }
}
